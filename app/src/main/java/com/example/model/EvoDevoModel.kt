/**
 * Biomechanical metrics derived from physical laws:
 * - Square-Cube Law: Mass scales with L^3, Cross-sectional strength scales with L^2
 * - Reynolds Number (Re = rho * v * L / mu): determines laminar/viscous vs inertial flow
 * - Fick's First Law: Diffusion time scales as x^2 / (2D)
 */
data class BiomechanicalMetrics(
    val bodyLengthMeters: Float,
    val massKg: Float,
    val skeletalYieldStressPercent: Float, // Stress / Yield strength (Failure if > 100%)
    val dailyMetabolicKj: Float, // Thermodynamic entropy cost Delta G
    val reynoldsNumber: Float, // Microbes < 1.0 (viscous), Macrofauna > 1000 (inertial)
    val vascularDiffusionSafety: Float // Must be > 1.0 to prevent internal hypoxia
)

/**
 * Procedural body plan segmentation generated by the Evo-Devo GRN.
 */
data class SegmentUnit(
    val segmentIndex: Int,
    val type: SegmentType,
    val widthFraction: Float, // 0.2 to 1.0
    val limbPairCount: Int, // 0, 1, 2
    val limbType: LimbType,
    val hasSpiracle: Boolean = false,
    val hasBranchialGill: Boolean = false
)

enum class SegmentType {
    CEPHALIC,
    THORACIC,
    ABDOMINAL,
    CAUDAL
}

enum class LimbType(val label: String, val dynamicCost: String) {
    NONE("None", "0 kJ"),
    CILIA_FLAGELLA("Cilia/Flagella", "Low (viscous creeping flow)"),
    JOINTED_WALKER("Jointed Exopod", "Medium (inverted pendulum gait)"),
    HYDROFOIL_FIN("Hydrofoil Fin", "Low-Medium (vortex lift generation)"),
    AERODYNAMIC_WING("Chitinous Wing", "High (requires elevated O₂ & light airframe)"),
    BIPEDAL_RAPTOR_LEG("Bipedal Pillar Leg", "High (inverted pendulum bipedal stride)"),
    PNEUMATIC_WING("Feathered Wing", "High (aerodynamic vortex downstroke)")
}

/**
 * Complete organism phenotype expressed from its virtual genome.
 */
data class OrganismPhenotype(
    val id: String,
    val binomialName: String,
    val commonName: String,
    val phylum: String,
    val activeCodons: List<CodonType>,
    val bodyLengthMeters: Float,
    val massKg: Float,
    val respirationSystem: String,
    val circulationSystem: String,
    val gaitDescription: String,
    val segments: List<SegmentUnit>,
    val biomechanics: BiomechanicalMetrics,
    val fitnessScore: Float, // 0.0 to 1.0
    val mutationRatePerGeneration: Float
)
